"""This host as a jobs worker: restarted and updated down a connection it opens.

`media restart-services --host NAME` and `media update --host NAME`, run on a
server, reach NAME down the stream NAME's jobs worker holds open to that
server (server phone_jobs.py, contract §6.21a). Nothing has to reach NAME:
no ssh, no Tailscale, no inbound port. The phone's worker is its own Termux
service (`deploy/phone/service/phone-jobs`); this is the same script for any
other host (`packages/core/services/jobs-worker`, run with `--generic`).

Setting a host up is two commands, one on each side:

* on the server: `media-visual-canvas pair --device "pn jobs" --jobs`
  (a jobs-only device: it takes restarts and updates, never a command, and
  its token opens no other route). It prints the line to run on the host:
* on the host: `media jobs pair '<sasonica://pair?server=…&code=…>'`. It
  trades the code at the server's `POST /pair`, keeps `{server, token,
  device_id, name}` in `~/.config/agent-media/jobs-worker.json` (0600), and
  installs the worker for this host's init (`install()`), started at once:

  - systemd --user: `agent-media-jobs-worker.service`, generated by
    media-setup (`ExecStart=/bin/sh <checkout>/…/jobs-worker/run`), enabled
    --now;
  - runit (Termux, or /etc/service): the template dir linked into the
    service dir (runsvdir starts it);
  - Windows: a logon task `agent-media\\jobs-worker` (Task Scheduler) running
    the script with this python under `conhost --headless`, restarted when
    it fails, started now.

`media-setup profile`'s `jobs` row keeps it installed (`row()`); `media jobs
status` says what is here. The phone (a `phone-jobs` runit service) is left
alone: that is its worker.
"""

from __future__ import annotations

import json
import os
import shutil
import socket
import subprocess
import sys
import time
from pathlib import Path
from typing import Callable, Optional

SERVICE = "jobs-worker"
UNIT = "agent-media-jobs-worker.service"
TASK = "agent-media\\jobs-worker"


def config_path() -> Path:
    """Where the worker script reads its pairing (jobs-worker.py CONFIG_FILE)."""
    return Path.home() / ".config" / "agent-media" / "jobs-worker.json"


def config() -> "Optional[dict]":
    try:
        got = json.loads(config_path().read_text())
    except (OSError, ValueError):
        return None
    return got if isinstance(got, dict) and got.get("token") and got.get("server") else None


def template_dir() -> Path:
    from . import setup

    return setup.service_templates_dir() / SERVICE


def script() -> Path:
    return template_dir() / "jobs-worker.py"


class JobsError(RuntimeError):
    pass


# --- pairing -----------------------------------------------------------------------


def pair(link: str, server: str = "") -> dict:
    """Trade a jobs pairing code (`pair --device NAME --jobs` on the server)
    for a token, and keep it. Returns the stored record, token included; its
    `warning` says when the server did not make it a jobs worker."""
    from . import peer_link

    link_server, code = peer_link.parse_link(link)
    base = (server or link_server).rstrip("/")
    if not code:
        raise JobsError("no pairing code in that link")
    if not base:
        raise JobsError("the link names no server: pass --server URL")
    me = socket.gethostname().split(".")[0]
    try:
        status, got = peer_link._http(base + "/pair", {"code": code, "device": f"{me} jobs"})
    except peer_link.PeerError as e:
        raise JobsError(str(e)) from e
    if status != 200 or not got.get("token"):
        raise JobsError(f"{base}/pair said {status}: {got.get('error') or got}")
    rec = {"server": base, "token": got["token"], "device_id": got.get("device_id"),
           "name": got.get("name"), "paired_at": time.strftime("%Y-%m-%dT%H:%M:%S%z")}
    path = config_path()
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(".tmp")
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as fh:
        json.dump(rec, fh, indent=2)
    os.replace(tmp, path)
    if not got.get("jobs"):
        rec["warning"] = (f"the server did not make {rec['name']!r} a jobs worker (a code "
                          "minted without --jobs, or a server too old for it), so it will "
                          f"not hand it jobs. On the server: media-visual-canvas devices "
                          f"--jobs {rec['device_id']}")
    return rec


# --- installing the service --------------------------------------------------------


def backend() -> str:
    """windows | runit | systemd | "" (none this knows)."""
    if os.name == "nt":
        return "windows"
    from . import setup

    if setup.services_dir() is not None:
        return "runit"
    if shutil.which("systemctl"):
        return "systemd"
    return ""


def phone_worker() -> bool:
    """This host is the phone: its worker is the `phone-jobs` runit service."""
    from . import setup

    sv = setup.services_dir()
    return bool(sv and ((sv / "phone-jobs").exists() or (sv / "phone-jobs").is_symlink()))


def _schtasks(*args: str) -> int:
    try:
        return subprocess.run(["schtasks", *args], capture_output=True, text=True,
                              timeout=60).returncode
    except (OSError, subprocess.SubprocessError):
        return 1


def _systemctl(*args: str) -> int:
    return subprocess.call(["systemctl", "--user", *args])


def task_arguments(python: str = "") -> str:
    """conhost's arguments for the Windows logon task: this python, the
    script, `--generic`, with no console window."""
    py = python or sys.executable
    return f'--headless "{py}" "{script()}" --generic'


def installed() -> bool:
    kind = backend()
    if kind == "windows":
        return _schtasks("/Query", "/TN", TASK) == 0
    from . import setup

    if kind == "runit":
        dest = setup.services_dir() / SERVICE
        return dest.exists() or dest.is_symlink()
    if kind == "systemd":
        return (setup.systemd_user_dir() / UNIT).exists()
    return False


def install(*, dry_run: bool = False, echo: "Callable[[str], None]" = print) -> bool:
    """Install (or keep) the worker for this host's init, started. Idempotent:
    a link already in place, a unit already current and a task already
    registered are left as they are."""
    from . import setup

    if phone_worker():
        echo("this host's jobs worker is its phone-jobs service: left alone")
        return True
    if getattr(sys, "frozen", False):
        # The single binary (`sasonica install`) carries no checkout to pull
        # and no python to run the worker with.
        echo("a binary install has no checkout for the worker to update: run it "
             "from a checkout (python3 and git), or update with `sasonica update`")
        return False
    kind = backend()
    if kind == "windows":
        return _install_windows(dry_run=dry_run, echo=echo)
    if kind == "runit":
        return setup._install_one_service(SERVICE, dry_run=dry_run,
                                          root=setup.services_dir())
    if kind == "systemd":
        unit = setup._install_one_systemd(SERVICE, dry_run=dry_run,
                                          root=setup.systemd_user_dir())
        if unit is None:
            return False
        if dry_run:
            echo(f"# would: systemctl --user daemon-reload && enable --now {unit}")
            return True
        _systemctl("daemon-reload")
        return _systemctl("enable", "--now", unit) == 0
    echo("no service manager here (systemd --user, runit or Windows): run "
         f"`python3 {script()} --generic` under whatever starts this host's programs")
    return False


def _install_windows(*, dry_run: bool, echo: "Callable[[str], None]") -> bool:
    """The logon task, from task XML (restart on failure) when the Sasonica
    package is here to write it, else a plain /SC ONLOGON task; started now."""
    args = task_arguments()
    what = "agent-media jobs worker: restarts and updates down its own connection"
    try:
        from sasonica import install as sas
    except ImportError:
        sas = None
    if dry_run:
        echo(f"# would register the logon task {TASK}: conhost.exe {args}")
        return True
    if sas is not None:
        rc = sas.register_task(TASK, sas.task_xml(args, sas._task_user(), what),
                               dry_run=False)
    else:
        rc = _schtasks("/Create", "/F", "/SC", "ONLOGON", "/RL", "LIMITED", "/TN", TASK,
                       "/TR", f"conhost.exe {args}")
    if rc != 0:
        echo(f"could not register the task {TASK} (schtasks rc {rc})")
        return False
    _schtasks("/End", "/TN", TASK)
    _schtasks("/Run", "/TN", TASK)
    echo(f"registered and started the logon task {TASK}")
    return True


def row(*, check_only: bool, dry_run: bool = False) -> "tuple[str, str]":
    """`media-setup profile`'s `jobs` row: ok, missing (paired, not
    installed), absent (not paired: nothing to run)."""
    if phone_worker():
        return "ok", "phone-jobs (the phone's worker)"
    cfg = config()
    if cfg is None:
        return "absent", "not paired: on the server, media-visual-canvas pair --device " \
                         "\"<host> jobs\" --jobs; here, media jobs pair '<link>'"
    where = f"{backend() or 'no init'}, {cfg.get('name') or cfg.get('device_id')} at {cfg['server']}"
    if installed():
        return "ok", where
    if check_only:
        return "missing", where
    return ("installed" if install(dry_run=dry_run) else "failed"), where


def status_lines() -> "list[str]":
    cfg = config()
    out = [f"init: {backend() or 'none known'}"]
    if phone_worker():
        out.append("worker: phone-jobs (this is the phone)")
        return out
    if cfg is None:
        out.append(f"paired: no ({config_path()} missing)")
    else:
        out.append(f"paired: {cfg.get('name')!r} ({cfg.get('device_id')}) with "
                   f"{cfg['server']}, {cfg.get('paired_at') or ''}".rstrip(", "))
    out.append(f"service: {'installed' if installed() else 'not installed'}")
    return out
